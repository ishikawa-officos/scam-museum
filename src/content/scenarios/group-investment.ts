/** グループでの発言 */
function g(
  id: string,
  speakerId: keyof typeof SPEAKERS,
  body: string,
  tactics: Message['tactics'] = [],
  note?: string,
): Message {
  return { id, speakerId, from: 'them', surface: 'group', body, tactics, note };
}

/** アシスタントとの個別トーク */
function dm(id: string, body: string, tactics: Message['tactics'] = [], note?: string): Message {
  return { id, speakerId: 'mayu', from: 'them', surface: 'chat', body, tactics, note };
}

function sys(id: string, body: string, surface: Message['surface'] = 'group'): Message {
  return { id, from: 'system', surface, body, tactics: [] };
}

